"""AGL(1, q) as a permutation group for 2BGA construction at prime-power q.

The metacyclic realization in group_algebra.py (``metacyclic(q, q-1, r)``)
covers Aff(F_q) only when F_q^+ is cyclic, i.e. q prime. For prime powers
(e.g. q = 16: n = 2*q*(q-1) = 480) F_q^+ is elementary abelian and the
affine group AGL(1, q) = F_q^+ |x F_q^* has to be built as a permutation
group instead. This module represents F_q as GF(2)[x] mod an irreducible
polynomial, encodes the affine maps x -> s*x + t as permutations of the q
field elements, and hands the Cayley table to ``build_2bga`` unchanged.

Group order check: |AGL(1, q)| = q * (q - 1) (F_q^* cyclic of order q-1,
generated by a primitive element of the chosen representation).
"""
import numpy as np

from group_algebra import perm_group, build_2bga  # noqa: F401  (re-exported)


def gf_tables(q, poly_bits):
    """Field GF(2)^deg for q = 2**deg given the irreducible poly's bitmask.

    ``poly_bits`` encodes the modulus polynomial with the bit for x**i (the
    leading x**deg bit is implied). Returns (exp, log) tables over 1..q-1
    for a generator that is the element ``x`` itself -- so ``poly_bits``
    must describe a PRIMITIVE polynomial for the multiplicative group to
    be generated by x (e.g. q=16: x^4 = x + 1, i.e. 0b0011).
    """
    deg = q.bit_length() - 1
    full = (1 << deg)  # the x**deg bit that reduction clears

    def mul(a, b):
        r = 0
        while b:
            if b & 1:
                r ^= a
            b >>= 1
            a <<= 1
            if a & full:
                a ^= poly_bits | full  # full modulus incl. the x**deg bit
        return r

    exp = [0] * (q - 1)
    log = [0] * q
    x = 2  # the element x
    v = 1
    for i in range(q - 1):
        exp[i] = v
        log[v] = i
        v = mul(v, x)
    assert v == 1 and len(set(exp)) == q - 1, "x is not primitive mod poly_bits"
    return exp, log, mul


def agl1(q, poly_bits):
    """Cayley table of AGL(1, q) acting on the q field elements.

    Returns (mul, elems) in the ``perm_group`` shape (identity at index 0)
    plus the (exp, log, mul_field) field tables for support sampling.
    """
    exp, log, fmul = gf_tables(q, poly_bits)

    def perm_mult_by_alpha_pow(i):
        # x -> alpha^i * x
        tbl = [0] * q
        for v in range(1, q):
            tbl[exp[(log[v] + i) % (q - 1)]] = v
        return tuple(tbl)

    def perm_translate(t):
        return tuple((v ^ t) for v in range(q))

    gens = [perm_mult_by_alpha_pow(1), perm_translate(1)]
    mul, elems = perm_group(gens, q)
    assert len(elems) == q * (q - 1), \
        f"AGL(1,{q}) should have order {q * (q - 1)}, got {len(elems)}"
    return mul, elems, (exp, log, fmul)


def sample_supports(mul, elems, field, rng, weight):
    """Draw a random weight-w support pair (a, b) of group-element indices.

    Mirrors the metacyclic lane's convention: uniform over distinct
    non-identity elements, a and b drawn independently.
    """
    exp, log, fmul = field
    n = len(elems)
    idx = list(range(1, n))
    a = sorted(rng.choice(idx, size=weight, replace=False).tolist())
    b = sorted(rng.choice(idx, size=weight, replace=False).tolist())
    return a, b


if __name__ == "__main__":
    # q=16: F_16 = GF(2)[x]/(x^4 + x + 1), x primitive.
    # poly_bits for x^4 + x + 1: bits 4..0 = 1 0011 -> the modulus stores the
    # low (deg) bits only: x+1 = 0b0011.
    mul, elems, field = agl1(16, 0b0011)
    print("AGL(1,16) order:", len(elems), "(expect 240); 2-block n =", 2 * len(elems))
    # smoke: a random draw builds a CSS pair
    import numpy as np
    rng = np.random.default_rng(1120)
    a, b = sample_supports(mul, elems, field, rng, 10)
    HX, HZ = build_2bga(mul, a, b)
    print("HX, HZ:", HX.shape, HZ.shape,
          "| commutes:", not (HX @ HZ % 2).any() if HX.shape == HZ.T.shape
          else "(shape check)", HX.shape, HZ.shape)
